// scripts/freeze-legacy-urls.mjs
// One-time freeze of the legacy POSITIONAL section URLs to their descriptive
// successors. The old scheme was:
//   /composition/:collection/composition/:index/section/:sectionId
// where :index came from the featured-then-title sort (see legacySort). That sort is
// used here exactly once — this is the last time positional order ever matters.
//
// Emits:
//   scripts/data/legacy-routes.json   — [{from,to}] commit-grade record
//   public/_redirects                 — GENERATED Netlify 301 rules (force: 301!)
//
// On Netlify, public/_redirects rules are evaluated before netlify.toml rules, so
// these 301s beat the SPA fallback in the toml.
//
// Cross-checks every positional URL in the CURRENT public/sitemap.xml against the
// mapping and aborts if any is unmapped (must be 100% coverage).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, READING_COLLECTIONS, loadCollection, legacySort } from './lib/content-model.mjs';

// Build the legacy positional -> canonical descriptive mapping.
const routes = [];
for (const collection of READING_COLLECTIONS) {
  const comps = legacySort(loadCollection(collection));
  comps.forEach((comp, i) => {
    const index = i + 1;
    const sections = Array.isArray(comp.sections) ? comp.sections : [];
    if (!comp.slug) throw new Error(`${collection}/${comp.filename}: missing composition slug (run enrich first)`);
    sections.forEach((section, s0) => {
      const s = s0 + 1;
      if (!section.slug) {
        throw new Error(`${collection}/${comp.filename} section[${s0}]: missing slug (run enrich first)`);
      }
      const from = `/composition/${collection}/composition/${index}/section/${s}`;
      const to =
        collection === 'constitutional'
          ? `/${comp.slug}/${section.slug}`
          : `/composition/${collection}/${comp.slug}/${section.slug}`;
      routes.push({ from, to });
    });
  });
}

// Cross-check: every positional URL in the current sitemap must be covered.
const sitemapPath = join(ROOT, 'public', 'sitemap.xml');
let sitemapPositional = [];
try {
  const xml = readFileSync(sitemapPath, 'utf8');
  const matches = xml.match(/\/composition\/[a-z]+\/composition\/\d+\/section\/\d+/g) || [];
  sitemapPositional = [...new Set(matches)];
} catch {
  console.warn('  ! could not read current sitemap.xml for cross-check');
}
const fromSet = new Set(routes.map((r) => r.from));
const misses = sitemapPositional.filter((u) => !fromSet.has(u));

console.log(`Legacy freeze: ${routes.length} positional route(s) mapped.`);
console.log(
  `Cross-check vs current sitemap: ${sitemapPositional.length} positional URL(s) present, ` +
    `${misses.length} unmapped.`,
);
if (misses.length > 0) {
  console.error('  UNMAPPED positional URLs (freeze is incomplete):');
  misses.forEach((u) => console.error(`    - ${u}`));
  process.exit(1);
}

// Static brand redirects (kirchner-v-trump -> kirchner-v-johnson).
const STATIC_REDIRECTS = [
  ['/kirchner-v-trump', '/kirchner-v-johnson'],
  ['/kirchner-v-trump/*', '/kirchner-v-johnson/:splat'],
];

// (a) commit-grade record
mkdirSync(join(ROOT, 'scripts', 'data'), { recursive: true });
writeFileSync(
  join(ROOT, 'scripts', 'data', 'legacy-routes.json'),
  `${JSON.stringify(routes, null, 2)}\n`,
);

// (b) generated _redirects
const lines = [
  '# GENERATED by scripts/freeze-legacy-urls.mjs — legacy positional URL freeze (301s). Do not hand-edit.',
];
for (const [from, to] of STATIC_REDIRECTS) lines.push(`${from} ${to} 301!`);
for (const { from, to } of routes) lines.push(`${from} ${to} 301!`);
writeFileSync(join(ROOT, 'public', '_redirects'), `${lines.join('\n')}\n`);

const ruleCount = STATIC_REDIRECTS.length + routes.length;
console.log(
  `Wrote scripts/data/legacy-routes.json (${routes.length} routes) and public/_redirects ` +
    `(${ruleCount} rules = ${STATIC_REDIRECTS.length} static + ${routes.length} positional).`,
);
